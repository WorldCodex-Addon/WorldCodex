-- Generates .luarc.json (lua-language-server config) from .luacheckrc so the globals live in one place.
-- Usage: luajit tools/luarc.lua           write .luarc.json
--        luajit tools/luarc.lua --check   exit 1 if .luarc.json is out of date (CI)

local env = { files = {} }
local chunk = assert(loadfile(".luacheckrc"))
setfenv(chunk, env)()

local names = {}
for _, list in ipairs({ env.globals, env.read_globals }) do
    for _, g in ipairs(list) do
        names[#names + 1] = string.format("%q", g)
    end
end

local out = table.concat({
    "{",
    '  "$schema": "https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json",',
    '  "//": "Generated by tools/luarc.lua from .luacheckrc - do not edit by hand.",',
    '  "runtime.version": "LuaJIT",',
    '  "runtime.builtin": { "io": "disable" },',
    '  "workspace.library": [],',
    '  "workspace.ignoreDir": [".release", "Libs", "Data"],',
    '  "workspace.checkThirdParty": false,',
    '  "diagnostics.globals": [' .. table.concat(names, ", ") .. "],",
    '  "diagnostics.disable": ["lowercase-global"]',
    "}",
    "",
}, "\n")

if arg[1] == "--check" then
    local f = io.open(".luarc.json", "rb")
    local current = f and f:read("*a")
    if f then f:close() end
    if current ~= out then
        io.stderr:write(".luarc.json is out of date: run luajit tools/luarc.lua\n")
        os.exit(1)
    end
else
    local f = assert(io.open(".luarc.json", "wb"))
    f:write(out)
    f:close()
end
